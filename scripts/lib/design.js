// 设计规则（把「旁门左道」的排版方法论落成可执行数值，而不是写在文档里靠自觉）
//
// 对应关系：
//   8pt 网格 / 间距分级  → 由「留白不是空，是在控制信息密度；模块间距 > 模块内间距 > 行距」
//   字号阶梯              → 由「先定层级再谈风格；主标题最大最重 / 信息点中等 / 注释最弱」
//   圆角三档              → 由「一页里不要同时出现太多圆角，收敛到 2–3 个值」
//   抬升（双层阴影+渐变） → 由「立体感来自统一光源：近处接触阴影 + 远处环境阴影」
//   信息密度上限          → 由「页面密度控制在 60% 以下，避免信息轰炸」
//   安全边距              → 由「四周预留安全边距，正文切忌贴边」
//
// 这些常量同时被版式引擎、验收脚本读取，改一处全局生效。

const IN = 1; // 单位：英寸
const pt = (v) => v / 72; // pt → in，保证落在真正的 4pt 网格上（不用 0.055 这类近似值）

// 1) 间距阶梯：以 4pt 为步长，只允许取这几档，避免"每个地方差一点点"
const SPACE = {
  xxs: pt(6),   //  6pt 行内微距（图标与文字）
  xs: pt(10),   // 10pt 元素内间距（标签与数值）
  sm: pt(18),   // 18pt 模块内间距
  md: pt(28),   // 28pt 模块间距（同级卡片之间）
  lg: pt(40),   // 40pt 区块间距（图文分栏之间）
  xl: pt(56),   // 56pt 版面级留白（页边到内容）
};

// 2) 字号阶梯：只有六档，且最小值 16pt。
//    字号一旦变小，页面就会"用字数换信息量"，讲台三米外看不清——所以这里直接设下限。
//    内容页通常只出现 3 种字号（标题 34 / 卡片标题 21 / 正文 18），层级靠字重和颜色补。
const MIN_FONT = 16;
const TYPE = {
  display: 52,  // 大字观点 / 封面主标题
  h1: 34,       // 内容页标题
  h2: 26,       // 区段标题 / 章节分隔标题
  h3: 21,       // 卡片标题、小标题
  body: 18,     // 正文
  small: 16,    // 辅助信息下限：页脚、来源、标签、坐标轴、图注
};

// 3) 圆角：只有三档。卡片、标签、胶囊各一个值，不再自由发挥
const RADIUS = {
  card: 0.16,   // 卡片、面板、答案底
  tag: 0.08,    // 小标签、序号块
  pill: 0.12,   // 胶囊导航
  none: 0,      // 色带、横幅（不要圆角，避免和卡片打架）
};

// 4) 抬升：立体感 = 统一光源 + 两级阴影 + 极轻渐变。
//    contact（接触阴影）贴边、短、稍实；ambient（环境阴影）远、软、淡。
//    只画一层阴影时卡片像"贴了张灰纸"，两层才像"浮起来"。
//    方向固定 90°（光源在正上方），透明度合计 ≤24%，否则会"发脏"。
const SHADOW = {
  // pptxgenjs 只支持单层，这一层是环境阴影；接触阴影由 postprocess.js 注入
  sm: { type: 'outer', color: '101820', blur: 14, offset: 5, angle: 90, opacity: 0.12 },
  md: { type: 'outer', color: '101820', blur: 26, offset: 9, angle: 90, opacity: 0.14 },
  none: undefined,
};

// 渐变：卡片上沿提亮 6%–8%，下沿压深 3%–5%。幅度必须小，否则像塑料。
const DEPTH = {
  topLighten: 0.42,  // 顶部与白色的混合比例（越大越亮）
  midAt: 0.52,       // 中间节点位置
  botDarken: 0.075,  // 底部压深比例
  // 接触阴影收紧、环境阴影放远：近处更“贴”、远处更“散”，浮起的间距才读得出来
  contact: { blur: 30000, dist: 14000, alpha: 0.22 },   // EMU / 万分比
  ambient: { blur: 460000, dist: 150000, alpha: 0.10 },
  inkColor: '101820',
  // 卡片描边做渐变（上亮下暗）：一条描边就能读出“板的厚度”，比加第二层形状可靠
  edgeLift: 0.34,    // 描边顶部提亮
  edgeDrop: 0.10,    // 描边底部压深
};

// 4b) 装饰语汇（ornament）：高级感来自"少量、克制、重复出现的细节"，而不是多条线
//     —— 金线只在结构分界处出现；角标只在"被强调的框"上出现；水印只用于深色页。
//     所有装饰对象统一以 decor. 开头命名，验收脚本据此把它排除在密度/边距统计外。
const ORN = {
  rule: 0.028,        // 金色细线厚度（in）≈ 2pt，投影下仍可见
  ruleTitle: 0.95,    // 标题下短金线长度
  bracket: 0.24,      // 角标臂长
  bracketW: 1.1,      // 角标线宽
  watermark: 6,       // 水印数字不透明度（%）
  gridAlpha: 7,       // 深色页网格不透明度（%）
  sheenAlpha: [2.6, 1.9, 1.3], // 三层柔光椭圆的不透明度（%）
  chipH: 0.34,        // 小标签（chip）高度
};

// 5) 密度与安全边距（字号变大后，密度必须跟着降，否则必挤）
const DENSITY_MAX = 0.55;  // 非背景元素覆盖面积上限
const SAFE_MARGIN = 0.72;  // 正文最小安全边距（in），当前版面 MX=0.85 留有余量
const CARD_PAD = pt(18);   // 卡片内边距：内容与卡片边缘至少留这么多
const MAX_BODY_LINES = 4;  // 卡片内正文不超过 4 行（18pt 下 5 行就成"念稿"了）

// 6) 导航（右上角胶囊）的呼吸区
//    胶囊不贴顶：上方留 0.54in（≈1.3 倍胶囊高），页头标题再整体下移避让，
//    使"胶囊 → 标题"之间保持 0.12in 的稳定间隙，而不是压在一起。
const NAV = {
  TAB_Y: 0.54,
  TAB_H: 0.46,
  TAB_GAP: 0.12,
  TAB_MAX_W: 8.6,
  HEADER_CLEAR: 0.30, // 胶囊模式下页头相对默认位置的下移量
};

// 阴影档位解析：允许字符串档位、对象、false
// 必须返回新对象——pptxgenjs 会就地改写传入的 shadow（pt→EMU），
// 若直接返回共享常量，每画一个形状就把数值再放大一轮（指数级）。
function shadowOf(v) {
  if (v === false || v === 'none') return undefined;
  if (v === undefined || v === null || v === true) return { ...SHADOW.sm };
  if (typeof v === 'string') return { ...(SHADOW[v] || SHADOW.sm) };
  return { ...v };
}

module.exports = {
  SPACE, TYPE, MIN_FONT, RADIUS, SHADOW, DEPTH, ORN,
  DENSITY_MAX, SAFE_MARGIN, CARD_PAD, MAX_BODY_LINES, NAV, shadowOf, pt,
};
